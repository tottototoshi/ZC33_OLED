// 画面消去関数
void cleardisplay() {
  u8g2.firstPage();
  do {
    u8g2.setDrawColor(0);
    u8g2.drawBox(0, 0, 255, 63);
    u8g2.setDrawColor(1);
  } while (u8g2.nextPage());
}

// ★追加・変更：Wi-Fi設定モード（APモード）に入った時に呼ばれるコールバック関数
void configModeCallback(WiFiManager *myWiFiManager) {
  u8g2.firstPage();
  do {
    u8g2.setFont(u8g_font_timR12);

    // 1行目："Wi-Fi Setup Mode" を中央に配置
    const char* title = "Wi-Fi Setup Mode";
    int titleWidth = u8g2.getStrWidth(title);
    u8g2.drawStr((256 - titleWidth) / 2, 15, title);
    
    // 2行目：スマホで繋ぐべきWi-Fi（SSID）の名前を中央に配置
    String ssidStr = "SSID: " + myWiFiManager->getConfigPortalSSID();
    int ssidWidth = u8g2.getStrWidth(ssidStr.c_str());
    u8g2.setCursor((256 - ssidWidth) / 2, 35);
    u8g2.print(ssidStr);
    
    // 3行目：ブラウザで開くIPアドレスを中央に配置
    // ※WiFiManagerのデフォルトIPは 192.168.4.1 固定です
    String ipStr = "IP: 192.168.4.1";
    int ipWidth = u8g2.getStrWidth(ipStr.c_str());
    u8g2.setCursor((256 - ipWidth) / 2, 55);
    u8g2.print(ipStr);

  } while (u8g2.nextPage());
  
  Serial.println("Entered config mode");
  Serial.println(myWiFiManager->getConfigPortalSSID());
}


void setup() {
  u8g2.begin();

  // ★変更：起動画面の表示
  // WiFi接続処理の前（ここ）で描画しておくことで、接続中は起動画面が維持されます
  u8g2.firstPage();
  do {
    u8g2.drawXBMP(60, 9, 120, 45, bootimg);
  } while (u8g2.nextPage());

  Serial.begin(115200);
  delay(100);
  
  //---------------------------------------------------------
  // WiFiManagerによる接続
  Serial.print("\n\nStart\n");
  
  WiFiManager wm;

  //テスト用リセット命令
  //wm.resetSettings(); // ★この1行を追加して書き込むと記憶が消去される
  
  // Wi-Fi接続のタイムアウト時間を60秒に設定
  wm.setConnectTimeout(60);
  
  // 設定モード（スマホからの入力待ち）のタイムアウト時間を120秒に設定
  wm.setConfigPortalTimeout(120);
  
  // 設定モードに入った時に画面表示を切り替える関数をセット
  wm.setAPCallback(configModeCallback);
  
  // 接続を試みる。「ESP32_Setup」は設定用Wi-Fiの名前
  // 接続完了またはタイムアウトするまでここで処理がブロックされます
  bool res = wm.autoConnect("ESP32_Setup");

  // 120秒の設定モード入力待ちをオーバーした場合
  if (!res) {
    Serial.println("Failed to connect and hit timeout. Restarting...");
    delay(1000);
    ESP.restart(); // ESP32を再起動してやり直す
  }

  // ここに到達したということはWi-Fi接続成功
  Serial.println();
  Serial.printf("Connected, IP address: ");
  Serial.println(WiFi.localIP());
  
//---------------------------------
  // ★変更：WiFi接続完了の表示（中央揃えでSSIDとIPを表示）
  u8g2.firstPage();
  do {
    u8g2.setFont(u8g_font_timR12);

    // 1行目："Connected!" を中央に配置
    const char* title = "Connected!";
    int titleWidth = u8g2.getStrWidth(title);
    u8g2.drawStr((256 - titleWidth) / 2, 20, title);
    
    // 2行目：SSID を中央に配置
    String ssidStr = "SSID: " + WiFi.SSID();
    int ssidWidth = u8g2.getStrWidth(ssidStr.c_str());
    u8g2.setCursor((256 - ssidWidth) / 2, 40);
    u8g2.print(ssidStr);
    
    // 3行目：IPアドレス を中央に配置
    String ipStr = "IP: " + WiFi.localIP().toString();
    int ipWidth = u8g2.getStrWidth(ipStr.c_str());
    u8g2.setCursor((256 - ipWidth) / 2, 60);
    u8g2.print(ipStr);
    
  } while (u8g2.nextPage());
  delay(3000);
  
  //-----------------------------------------------------------
  //時間同期
  configTime(JST, 0, "ntp.nict.jp", "ntp.jst.mfeed.ad.jp");
  
  //-----------------------------------------------------------
  //消去
  cleardisplay();
  delay(1000);

  //----------------------------------------------------------------------
  //センサー開始
  dht.begin();
  
  //--------------------------------------------------------------------
  //センサー読み取り周期処理設定
  prev = 0;         // 前回実行時刻を初期化
  interval = 2000;  // 実行周期を設定
}

void loop() {
  //---------------------------------------------------------------
  //センサー読み取り周期処理開始
  unsigned long curr = millis();    // 現在時刻を取得
  if ((curr - prev) >= interval) {  // 前回実行時刻から実行周期以上経過していたら
    i = i + 1;

    //センサー値取得
    bool isFahrenheit = true;
    float percentHumidity = dht.readHumidity();          //湿度取得
    float temperature = dht.readTemperature();           //温度取得
    if (isnan(percentHumidity) || isnan(temperature)) {  //エラー処理
      Serial.println("ERROR");
      return;
    }

    //10回平均を出す
    if (i <= 10) {                      //9回目までは
      prete = prete + temperature;      //累積していく
      prehu = prehu + percentHumidity;  //累積していく
      Serial.print(i);
      Serial.println(",");
    } else {                       //10回目なら
      preteave = prete / 10 - 1;   //平均する＆補正
      prehuave = prehu / 10 - 10;  //平均する&補正
      te = String(preteave, 1);    //桁揃えした温度を代入
      hu = String(prehuave, 0);    //桁揃えした湿度を代入
      i = 0;
      prete = 0;
      prehu = 0;
      Serial.print(" : ");
      Serial.println(te);
    }
    prev = curr;  // 前回実行時刻を現在時刻で更新
  }
  // 周期処理終了-----------------------------------------------------

  //-------------------------------------------------------------
  //時計処理
  time_t t;                                                                      //time_t型
  struct tm* tm;                                                                 //構造体定義
  static const char* wd[7] = { "Sun", "Mon", "Tue", "Wed", "Thr", "Fri", "Sat" };  //曜日
  t = time(NULL);
  tm = localtime(&t);
  Serial.printf(" %04d/%02d/%02d(%s) %02d:%02d:%02d\n",
                tm->tm_year + 1900, tm->tm_mon + 1, tm->tm_mday,
                wd[tm->tm_wday],
                tm->tm_hour, tm->tm_min, tm->tm_sec);
  delay(1000);

  //表示---------------------------------------------
  u8g2.firstPage();
  do {
    //温度湿度
    u8g2.setFont(u8g_font_timR12);
    u8g2.drawStr(20, 15, "temp");
    u8g2.setCursor(65, 15);
    u8g2.print(te);                     //桁揃え温度表記
    u8g2.drawXBMP(97, 3, 13, 13, doC);  //℃表記
    u8g2.drawStr(135, 15, "humid");
    u8g2.setCursor(185, 15);
    u8g2.print(hu);  //桁揃え湿度表記
    u8g2.drawStr(205, 15, "%");

    //時計
    hourXpoint = 75;   //時X座標
    minXpoint = 140;   //分X座標
    secXpoint = 195;   //秒X座標
    monthXpoint = 25;  //月X座標
    dayXpoint = 42;    //日X座標

    if (tm->tm_hour < 10) {          //時が10以下だったら
      hourXpoint = hourXpoint + 25;  //オフセットさせる
    }
    if (tm->tm_min < 10) {  //分が10以下だったら
      u8g2.setFont(u8g2_font_logisoso38_tf);
      u8g2.drawStr(minXpoint, 63, "0");  //0を接頭させる
      minXpoint = minXpoint + 25;        //オフセットさせる
    }
    if (tm->tm_sec < 10) {  //秒が10以下だったら
      u8g2.setFont(u8g_font_timR12);
      u8g2.drawStr(secXpoint, 60, "0");  //0を接頭させる
      secXpoint = secXpoint + 8;         //オフセットさせる
    }
    if (tm->tm_mon + 1 < 10) {
      monthXpoint = monthXpoint + 5;  //オフセットさせる
    }
    if (tm->tm_mday < 10) {
      dayXpoint = dayXpoint + 5;  //オフセットさせる
    }

    u8g2.setFont(u8g2_font_logisoso38_tf);
    u8g2.setCursor(hourXpoint, 63);  //時
    u8g2.print(tm->tm_hour);
    u8g2.drawStr(125, 63, ":");
    u8g2.setCursor(minXpoint, 63);  //分
    u8g2.print(tm->tm_min);
    u8g2.setFont(u8g_font_timR12);
    u8g2.setCursor(monthXpoint, 42);  //月/日
    u8g2.print(tm->tm_mon + 1);
    u8g2.print(" / ");
    u8g2.print(tm->tm_mday);
    u8g2.setCursor(27, 58);  //曜日
    u8g2.print("(");
    u8g2.print(wd[tm->tm_wday]);
    u8g2.print(")");
    u8g2.setCursor(secXpoint, 60);  //秒
    u8g2.print(tm->tm_sec);
    u8g2.drawLine(15, 18, 220, 18);  //横線

  } while (u8g2.nextPage());
}